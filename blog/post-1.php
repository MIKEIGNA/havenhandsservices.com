            <p>Hiring a nanny is one of the most critical decisions you will make for your home. In Nairobi's fast-paced environment, parents need peace of mind knowing their children are in safe, competent, and ethical hands. While reference checks and background vetting are essential steps in the hiring process, the interview is your best opportunity to gauge a candidate's personality, communication style, and child-rearing philosophy.</p>

            <p>To help you navigate this process, we have compiled the five essential questions you should ask every candidate during an interview.</p>

            <h2>1. "Can you describe a time when a child in your care had an emergency, and how you handled it?"</h2>
            <p>This is a behavioral question designed to evaluate the candidate's crisis management skills, problem-solving capability, and composure under pressure. Listen closely to how they describe the emergency. Did they panic, or did they immediately administer basic first aid and contact the parent or emergency services?</p>
            <p><strong>What to look for:</strong> Look for knowledge of basic first aid rules (such as choking responses, wound dressing, or high-fever protocols) and a clear understanding of when to call for emergency assistance.</p>

            <h2>2. "What are your strategies for managing toddlers' tantrums or child behavior challenges?"</h2>
            <p>Discipline philosophies vary widely. It is critical that your nanny's approach to behavior management aligns with yours. Asking this question helps you avoid future conflicts regarding physical punishment, shouting, or emotional neglect.</p>
            <p><strong>What to look for:</strong> Look for positive reinforcement methods, redirection strategies, calm communication, and a refusal to use physical force or abusive language. A professional nanny should understand positive discipline.</p>

            <h2>3. "How do you plan a child's daily schedule to balance play, learning, and rest?"</h2>
            <p>A nanny's role goes beyond basic supervision. A professional nanny is an active contributor to early childhood development. This question allows you to assess their planning skills and child engagement methods.</p>
            <p><strong>What to look for:</strong> Strategies that limit screen time, age-appropriate educational games, regular nap routines, outdoor play coordination, and homework support for older children.</p>

            <h2>4. "How do you handle communication when you and the employer have differing opinions?"</h2>
            <p>Domestic service requires a high degree of workplace etiquette and soft communication skills. Differing opinions on child care, food choices, or working hours are natural. What matters is how these issues are resolved.</p>
            <p><strong>What to look for:</strong> Active listening, respectful reporting, willingness to follow parental instructions, and proactive communication before issues escalate.</p>

            <h2>5. "What professional domestic training or certifications do you hold?"</h2>
            <p>Vetting and formal credentials elevate a candidate from a simple housekeeper to a professional Staff. In Nairobi, training in safety, digital literacy, and nutrition makes a Staff much more reliable.</p>
            <p><strong>What to look for:</strong> Certifications in child care basics, home safety/first aid, kitchen hygiene, and general professional conduct. Certifications from recognized agencies like Haven Hands show a commitment to career growth.</p>

